// Builds the diagram viewer pages that the plugin loads into a sandboxed iframe.
//
//   pnpm build:viewer
//
// Run it after bumping `bpmn-js` / `dmn-js` in package.json or after editing
// public/viewer/viewer.{js,css}, and commit the result.
//
// Why a separate page? Discourse sends a strict, nonce-based Content Security
// Policy. An iframe created with `srcdoc` inherits that policy, so inline
// scripts and scripts from a CDN cannot run in it. A real page served from the
// plugin's public/ directory gets no Discourse CSP and only loads files that
// are shipped with the plugin.
//
// nginx serves public/ files with `Cache-Control: immutable` for a year, so
// every URL produced here carries a content hash as a cache buster.

/* eslint-disable no-console -- command line script */

import { createHash } from "node:crypto";
import { copyFile, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const VIEWER_DIR = join(ROOT, "public/viewer");
const VENDOR_DIR = join(VIEWER_DIR, "vendor");
const URLS_MODULE = join(
  ROOT,
  "assets/javascripts/discourse/lib/bpmn-io-viewer-urls.js"
);
const PUBLIC_PATH = "/plugins/discourse-bpmn-io/viewer";
const GENERATED_NOTICE =
  "Generated by `pnpm build:viewer` (scripts/build-viewer.mjs). Do not edit.";

const VIEWERS = {
  bpmn: {
    title: "BPMN diagram preview",
    library: "bpmn-js",
    files: [
      "dist/assets/diagram-js.css",
      "dist/assets/bpmn-js.css",
      "dist/bpmn-navigated-viewer.production.min.js",
    ],
  },
  dmn: {
    title: "DMN diagram preview",
    library: "dmn-js",
    files: [
      "dist/assets/diagram-js.css",
      "dist/assets/dmn-js-shared.css",
      "dist/assets/dmn-js-drd.css",
      "dist/assets/dmn-js-decision-table.css",
      "dist/assets/dmn-js-literal-expression.css",
      "dist/assets/dmn-js-boxed-expression.css",
      // icon font inlined as data: URIs, so no cross-origin font requests
      // are needed from the sandboxed (opaque origin) document
      "dist/assets/dmn-font/css/dmn-embedded.css",
      "dist/dmn-navigated-viewer.production.min.js",
    ],
  },
};

function hash(content) {
  return createHash("sha256").update(content).digest("hex").slice(0, 12);
}

async function versioned(relativePath) {
  const content = await readFile(join(VIEWER_DIR, relativePath));
  return `${relativePath}?v=${hash(content)}`;
}

async function vendorLibrary(library, files) {
  const packageDir = join(ROOT, "node_modules", library);
  const { version } = JSON.parse(
    await readFile(join(packageDir, "package.json"), "utf8")
  );
  const target = join(VENDOR_DIR, `${library}-${version}`);
  await mkdir(target, { recursive: true });
  await copyFile(join(packageDir, "LICENSE"), join(target, "LICENSE"));

  const copied = [];
  for (const file of files) {
    await copyFile(join(packageDir, file), join(target, basename(file)));
    copied.push(`vendor/${library}-${version}/${basename(file)}`);
  }
  return copied;
}

function renderPage({ type, title, styles, scripts }) {
  const links = styles.map(
    (href) => `    <link rel="stylesheet" href="${href}" />`
  );
  const tags = scripts.map((src) => `    <script src="${src}"></script>`);

  return `<!doctype html>
<!-- ${GENERATED_NOTICE} -->
<html lang="en" data-diagram-type="${type}">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <meta name="robots" content="noindex" />
    <title>${title}</title>
${links.join("\n")}
  </head>
  <body>
    <div id="container"></div>
    <div id="error" class="error" role="alert" hidden></div>
${tags.join("\n")}
  </body>
</html>
`;
}

async function build() {
  await rm(VENDOR_DIR, { recursive: true, force: true });

  const urls = {};
  for (const [type, viewer] of Object.entries(VIEWERS)) {
    const vendored = await vendorLibrary(viewer.library, viewer.files);
    const assets = await Promise.all(
      [...vendored, "viewer.css", "viewer.js"].map(versioned)
    );

    const page = renderPage({
      type,
      title: viewer.title,
      styles: assets.filter((path) => path.includes(".css?")),
      scripts: assets.filter((path) => path.includes(".js?")),
    });
    await writeFile(join(VIEWER_DIR, `${type}.html`), page);

    urls[type] = `${PUBLIC_PATH}/${type}.html?v=${hash(page)}`;
    console.log(`public/viewer/${type}.html (${viewer.library})`);
  }

  const entries = Object.entries(urls).map(
    ([type, url]) => `  ${type}: "${url}",`
  );
  await writeFile(
    URLS_MODULE,
    `// ${GENERATED_NOTICE}\nexport default {\n${entries.join("\n")}\n};\n`
  );
  console.log("assets/javascripts/discourse/lib/bpmn-io-viewer-urls.js");
}

await build();
